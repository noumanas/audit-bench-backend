const lines = (...l: string[]) => l.join('\n');
const all = (code: string) => [{ start: 1, end: code.split('\n').length }];

const c = (id: string, title: string, path: string, code: string, bugs: BenchmarkCase['bugs']): BenchmarkCase => ({
  id,
  title,
  path,
  code,
  changed: all(code),
  bugs,
});

