/** Why a file in the repository wasn't reviewed — listed in the report so nothing is skipped silently. */
export type SkipReason =
  | 'ignored_by_rule'
  | 'generated'
  | 'vendor'
  | 'not_source'
  | 'file_limit'
  | 'too_large'
  | 'binary';

export interface SkippedFile {
  path: string;
  reason: SkipReason;
}

/** Most entries a report stores; the counts per reason are always complete. */
export const MAX_SKIPPED_LISTED = 500;

// Tool output, not code anyone wrote or should review: designer files,
// migrations snapshots, protobuf/gRPC stubs, resource files, minified bundles.
const GENERATED_PATH = [
  /\.designer\.(cs|vb)$/i,
  /\.g\.(i\.)?cs$/i,
  /\.generated\.\w+$/i,
  /(^|\/)AssemblyInfo\.(cs|vb)$/i,
  /(^|\/)Reference\.cs$/i,
  /ModelSnapshot\.cs$/i,
  /(^|\/)Migrations\/\d{8,}_[^/]+\.(cs|Designer\.cs)$/i,
  /\.resx$/i,
  /\.pb\.(go|cc|h)$/i,
  /_pb2(_grpc)?\.py$/i,
  /\.min\.(js|css)$/i,
  /\.(js|css)\.map$/i,
  /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|composer\.lock|Gemfile\.lock|poetry\.lock|Cargo\.lock|packages\.lock\.json)$/i,
];

const GENERATED_HEADER =
  /<auto-generated|@generated\b|Code generated .* DO NOT EDIT|This (file|code) was (automatically|auto-)generated|Generated by the protocol buffer compiler/i;

// Third-party code copied into the repository rather than installed.
const VENDOR_PATH = [
  /(^|\/)(vendor|vendors|third_party|thirdparty|external|bower_components|node_modules)\//i,
  /(^|\/)wwwroot\/lib\//i,
  /(^|\/)(obj|bin)\/(Debug|Release)\//i,
  /(^|\/)(jquery|bootstrap|popper|modernizr|respond|angular|react|lodash|moment)([.-][\w.-]*)?\.js$/i,
  /(^|\/)jquery\.validate[\w.-]*\.js$/i,
];

/**
 * Generated or third-party code: excluded from the AI review and from the
 * duplicate, dead-code and coverage checks by default, since flagging a
 * WinForms designer file or a copy of jQuery is noise, not a finding.
 * Generated files are still scanned for secrets (a Settings.Designer.cs can
 * hold a real connection string); vendor files are not.
 */
export function classifyNonAuthored(path: string, content = ''): 'generated' | 'vendor' | null {
  if (VENDOR_PATH.some((re) => re.test(path))) return 'vendor';
  if (GENERATED_PATH.some((re) => re.test(path))) return 'generated';
  if (GENERATED_HEADER.test(content.slice(0, 600))) return 'generated';
  return null;
}
